import './canvasWorkspace.css';
import type { useCanvasDocumentEffects } from './useCanvasDocumentEffects';
export function renderCanvasHeader(
  context: ReturnType<typeof useCanvasDocumentEffects> & { batchSourceNodeIds: string[] },
) {
  const {
    React,
    Header,
    chatPanelWidth,
    savedAt,
    savedBy,
    savedRevision,
    isChatOpen,
    canvasTitle,
    setCanvasTitle,
    isEditingTitle,
    setIsEditingTitle,
    editingTitleValue,
    setEditingTitleValue,
    canvasTitleInputRef,
    getWorkflowEpoch,
    workflowId,
    switchProject,
    hasUnsavedChanges,
    save,
    chooseProjectFile,
    exportWorkflow,
    transferring,
    backToProjects,
    readOnly,
  } = context;
  return React.createElement(Header, {
    key: 'header',
    canvasTitle,
    isEditingTitle,
    editingTitleValue,
    canvasTitleInputRef,
    setCanvasTitle,
    setIsEditingTitle,
    setEditingTitleValue,
    onSave: () => save({ manual: true, reportFailure: true }),
    documentEpoch: getWorkflowEpoch(),
    currentProjectId: workflowId,
    onSwitchProject: switchProject,
    onBack: () => backToProjects(true),
    onImportWorkflow: chooseProjectFile,
    onExportWorkflow: exportWorkflow,
    transferring,
    hasUnsavedChanges,
    isChatOpen,
    chatPanelWidth,
    lastAutoSaveTime: savedAt,
    lastSavedBy: savedBy,
    lastSavedRevision: savedRevision,
    readOnly,
  });
}
