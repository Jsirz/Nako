import './canvasWorkspace.css';
import type { useCanvasDocumentEffects } from './useCanvasDocumentEffects';
export function renderCanvasContextOverlays(
  context: ReturnType<typeof useCanvasDocumentEffects> & { batchSourceNodeIds: string[] },
) {
  const {
    React,
    Overlays,
    contextMenu,
    setContextMenu,
    expandedImageUrl,
    expandedComparePayload,
    expandedCompositePayload,
    handleCloseExpand,
    handleCloseCompare,
    handleCloseComposite,
    canvasTitle,
    cancelConnectionDrag,
    canUndo,
    canRedo,
    undo,
    redo,
    isCreateAssetModalOpen,
    setIsCreateAssetModalOpen,
    nodeToSnapshot,
    assetCategories,
    handleSaveAssetToLibrary,
    handleContextUpload,
    handleCopy,
    handlePaste,
    handleContextMenuCreateAsset,
    handleContextMenuCopyImage,
    handleContextMenuSelect,
    openAssetsModal,
    readOnly,
  } = context;
  return React.createElement(Overlays, {
    key: 'overlays',
    contextMenu: readOnly ? { ...contextMenu, isOpen: false } : contextMenu,
    onCloseContextMenu: () => {
      setContextMenu((ke) => ({ ...ke, isOpen: false }));
      cancelConnectionDrag();
    },
    onSelectType: readOnly ? () => {} : handleContextMenuSelect,
    onUpload: readOnly ? () => {} : handleContextUpload,
    onUndo: readOnly ? () => {} : undo,
    onRedo: readOnly ? () => {} : redo,
    onPaste: readOnly ? () => {} : handlePaste,
    onCopy: readOnly ? () => {} : handleCopy,
    onCreateAsset: readOnly ? () => {} : handleContextMenuCreateAsset,
    onCopyImage: handleContextMenuCopyImage,
    onAddAssets: readOnly ? () => {} : openAssetsModal,
    canUndo: !readOnly && canUndo,
    canRedo: !readOnly && canRedo,
    expandedImageUrl,
    expandedComparePayload,
    expandedCompositePayload,
    onCloseExpand: handleCloseExpand,
    onCloseCompare: handleCloseCompare,
    onCloseComposite: handleCloseComposite,
    isCreateAssetModalOpen: !readOnly && isCreateAssetModalOpen,
    setIsCreateAssetModalOpen,
    nodeToSnapshot,
    assetCategories,
    assetDefaultOwnership: canvasTitle,
    onSaveAssetToLibrary: readOnly ? () => {} : handleSaveAssetToLibrary,
  });
}
