import './canvasWorkspace.css';
import type { useCanvasDocumentState } from './useCanvasDocumentState';

export function useCanvasConnectionState(context: ReturnType<typeof useCanvasDocumentState>) {
  const {
    useConnections,
    useDrag,
    useResize,
    useMarquee,
    useGroups,
    useEdgePan,
    useHistory,
    useWorkflow,
    view,
    isMinimapOpen,
    setMinimapOpen,
    closeHistoryPanel,
    closeAssetLibrary,
    closeWorkflowPresetPanel,
    canvasTitle,
    setCanvasTitle,
    setEditingTitleValue,
    viewport,
    setViewport,
    canvasRef,
    nodes,
    setNodes,
    selectedNodeIds,
    setSelectedNodeIds,
  } = context;

  const {
      isDraggingConnection,
      isPendingConnection,
      connectionStart,
      tempConnectionEnd,
      hoveredNodeId: connectionHoveredNodeId,
      hoveredSide,
      hoveredPortIndex,
      isInvalidHover,
      selectedConnection,
      setSelectedConnection,
      pendingBatchSourceNodeIds,
      handleConnectorPointerDown,
      updateConnectionDrag,
      completeConnectionDrag,
      cancelConnectionDrag,
      handleEdgeClick,
      deleteSelectedConnection,
    } = useConnections(),
    {
      handleNodePointerDown,
      updateNodeDrag,
      endNodeDrag,
      startPanning,
      updatePanning,
      endPanning,
      isDragging,
      isPanning,
      releasePointerCapture,
    } = useDrag(),
    {
      isResizing,
      handleResizeStart,
      handleSelectionResizeStart: startSelectionResize,
      updateNodeResize,
      endNodeResize,
    } = useResize(),
    {
      selectionBox,
      isSelecting,
      startSelection,
      updateSelection,
      endSelection,
      clearSelectionBox,
    } = useMarquee(),
    {
      groups,
      setGroups,
      getGroups,
      groupNodes,
      ungroupNodes,
      cleanupInvalidGroups,
      getCommonGroup,
      renameGroup,
    } = useGroups(),
    { updatePointerPos } = useEdgePan({
      canvasRef,
      isDragging,
      isDraggingConnection,
      isSelecting,
      viewport,
      setViewport,
      setNodes,
      selectedNodeIds,
    }),
    {
      undo: undoHistory,
      redo: redoHistory,
      pushHistory,
      reset,
      canUndo,
      canRedo,
    } = useHistory({ nodes, groups }, 50);

  const {
      workflowId,
      isWorkflowPanelOpen,
      workflowPanelY,
      handleSaveWorkflow,
      handleLoadWorkflow,
      closeWorkflowPanel,
      resetWorkflowId,
      getWorkflowEpoch,
      importDocument,
      useProjectFiles,
      useProjectTransfer,
      useSaveFeedback,
    } = useWorkflow({
      nodes,
      groups,
      viewport,
      canvasTitle,
      isMinimapOpen,
      setNodes,
      setGroups,
      setSelectedNodeIds,
      setCanvasTitle,
      setEditingTitleValue,
      setViewport,
      setIsMinimapOpen: setMinimapOpen,
      onPanelOpen: () => {
        closeHistoryPanel();
        closeAssetLibrary();
        closeWorkflowPresetPanel();
      },
    }),
    activeProjectId = view === 'canvas' ? workflowId : null;
  return {
    ...context,
    isDraggingConnection,
    isPendingConnection,
    connectionStart,
    tempConnectionEnd,
    connectionHoveredNodeId,
    hoveredSide,
    hoveredPortIndex,
    isInvalidHover,
    selectedConnection,
    setSelectedConnection,
    pendingBatchSourceNodeIds,
    handleConnectorPointerDown,
    updateConnectionDrag,
    completeConnectionDrag,
    cancelConnectionDrag,
    handleEdgeClick,
    deleteSelectedConnection,
    handleNodePointerDown,
    updateNodeDrag,
    endNodeDrag,
    startPanning,
    updatePanning,
    endPanning,
    isDragging,
    isPanning,
    releasePointerCapture,
    isResizing,
    handleResizeStart,
    startSelectionResize,
    updateNodeResize,
    endNodeResize,
    selectionBox,
    isSelecting,
    startSelection,
    updateSelection,
    endSelection,
    clearSelectionBox,
    groups,
    setGroups,
    getGroups,
    groupNodes,
    ungroupNodes,
    cleanupInvalidGroups,
    getCommonGroup,
    renameGroup,
    updatePointerPos,
    undoHistory,
    redoHistory,
    pushHistory,
    reset,
    canUndo,
    canRedo,
    workflowId,
    isWorkflowPanelOpen,
    workflowPanelY,
    handleSaveWorkflow,
    handleLoadWorkflow,
    closeWorkflowPanel,
    resetWorkflowId,
    getWorkflowEpoch,
    importDocument,
    useProjectFiles,
    useProjectTransfer,
    useSaveFeedback,
    activeProjectId,
  };
}
