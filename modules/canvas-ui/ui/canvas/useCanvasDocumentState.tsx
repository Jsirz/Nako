import type * as ReactTypes from 'react';
import './canvasWorkspace.css';
import type { useCanvasWorkspaceState } from './useCanvasWorkspaceState';

export function useCanvasDocumentState(context: ReturnType<typeof useCanvasWorkspaceState>) {
  const { React, usePanels, useTitle, useViewport, useNodes } = context;

  const {
      isHistoryPanelOpen,
      historyPanelY,
      handleHistoryClick,
      closeHistoryPanel,
      expandedImageUrl,
      expandedComparePayload,
      expandedCompositePayload,
      handleExpandImage,
      handleOpenCompare,
      handleOpenComposite,
      handleCloseExpand,
      handleCloseCompare,
      handleCloseComposite,
      isChatOpen,
      toggleChat,
      closeChat,
      isAssetLibraryOpen,
      assetLibraryY,
      assetLibraryVariant,
      handleAssetsClick,
      closeAssetLibrary,
      openAssetLibraryModal,
      isWorkflowPresetPanelOpen,
      workflowPresetPanelY,
      closeWorkflowPresetPanel,
      isDraggingNodeToChat,
      handleNodeDragStart,
      handleNodeDragEnd,
      annotatingNodeId,
      handleStartAnnotation,
      handleCloseAnnotation,
      cropNodeId,
      imageEditorMode,
      handleStartCrop,
      handleCloseCrop,
      resizeNodeId,
      handleStartResize,
      handleCloseResize,
    } = usePanels(),
    [batchConnecting, setBatchConnecting] = React.useState(false),
    selectedCoverRef = React.useRef<string | null>(null),
    newProjectPendingRef = React.useRef(false);
  const {
      canvasTitle,
      setCanvasTitle,
      isEditingTitle,
      setIsEditingTitle,
      editingTitleValue,
      setEditingTitleValue,
      canvasTitleInputRef,
    } = useTitle(),
    { viewport, setViewport, canvasRef, handleWheel, handleSliderZoom, focusOnNodes } =
      useViewport(),
    onCanvasWheel = (ke: ReactTypes.WheelEvent<HTMLDivElement>) => {
      handleWheel(ke);
    },
    {
      nodes,
      setNodes,
      getNodes,
      createAgentNode,
      configureAgentNode,
      connectAgentNodes,
      selectedNodeIds,
      setSelectedNodeIds,
      updateNode,
      deleteNodes,
      clearSelection,
      handleSelectTypeFromMenu,
      autoAlignNodes,
      gridLayoutNodes,
    } = useNodes(),
    focusNodes = React.useCallback(
      (nodeIds: readonly string[]) => focusOnNodes(getNodes(), nodeIds),
      [focusOnNodes, getNodes],
    );
  return {
    ...context,
    isHistoryPanelOpen,
    historyPanelY,
    handleHistoryClick,
    closeHistoryPanel,
    expandedImageUrl,
    expandedComparePayload,
    expandedCompositePayload,
    handleExpandImage,
    handleOpenCompare,
    handleOpenComposite,
    handleCloseExpand,
    handleCloseCompare,
    handleCloseComposite,
    isChatOpen,
    toggleChat,
    closeChat,
    isAssetLibraryOpen,
    assetLibraryY,
    assetLibraryVariant,
    handleAssetsClick,
    closeAssetLibrary,
    openAssetLibraryModal,
    isWorkflowPresetPanelOpen,
    workflowPresetPanelY,
    closeWorkflowPresetPanel,
    isDraggingNodeToChat,
    handleNodeDragStart,
    handleNodeDragEnd,
    annotatingNodeId,
    handleStartAnnotation,
    handleCloseAnnotation,
    cropNodeId,
    imageEditorMode,
    handleStartCrop,
    handleCloseCrop,
    resizeNodeId,
    handleStartResize,
    handleCloseResize,
    batchConnecting,
    setBatchConnecting,
    selectedCoverRef,
    newProjectPendingRef,
    canvasTitle,
    setCanvasTitle,
    isEditingTitle,
    setIsEditingTitle,
    editingTitleValue,
    setEditingTitleValue,
    canvasTitleInputRef,
    viewport,
    setViewport,
    canvasRef,
    handleWheel,
    handleSliderZoom,
    focusOnNodes,
    onCanvasWheel,
    nodes,
    setNodes,
    getNodes,
    createAgentNode,
    configureAgentNode,
    connectAgentNodes,
    selectedNodeIds,
    setSelectedNodeIds,
    updateNode,
    deleteNodes,
    clearSelection,
    handleSelectTypeFromMenu,
    autoAlignNodes,
    gridLayoutNodes,
    focusNodes,
  };
}
